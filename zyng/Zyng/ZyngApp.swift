import SwiftUI

// @MainActor обязателен.
//
// В проекте выбрана изоляция по умолчанию nonisolated, поэтому ни App, ни View
// главному актору сами по себе не принадлежат. А всё, что мы трогаем при
// запуске — настройки, список серверов, управление туннелем, — помечено
// @MainActor. Без этой строки обращение к ним из init считается выходом за
// пределы актора.
@main
@MainActor
struct ZyngApp: App {

    /// Отметки запуска.
    ///
    /// Приложение показывает чёрный экран: процесс жив, но до первой отрисовки
    /// дело не доходит. Снаружи такое неотличимо — что подпись, что зависание,
    /// что сбой в разборе сохранённых ключей выглядят одинаково.
    ///
    /// Поэтому пусть приложение само расскажет, куда добралось. Каждая отметка
    /// печатается в консоль, и по последней видно, на чём оно встало. Строки
    /// короткие и без содержимого ключей — их не стыдно оставить и в релизе.
    init() {
        NSLog("🟢 Zyng: старт приложения")

        // Тяжёлое из запуска трогаем ЗДЕСЬ и по одному, а не в свойствах
        // ContentView. Там всё создаётся разом, и если что-то встанет, узнать
        // что именно уже нельзя: экран просто остаётся чёрным.
        NSLog("🟢 Zyng: читаю настройки…")
        _ = AppSettings.shared
        NSLog("🟢 Zyng: настройки прочитаны")

        NSLog("🟢 Zyng: читаю список серверов…")
        _ = ServerStore.shared
        NSLog("🟢 Zyng: список серверов прочитан")

        NSLog("🟢 Zyng: поднимаю управление туннелем…")
        _ = VPNController.shared
        NSLog("🟢 Zyng: управление туннелем готово")
    }

    var body: some Scene {
        WindowGroup {
            // Тему выбирает пользователь — ContentView применяет её сам.
            // Жёсткое .dark здесь перекрывало этот выбор.
            ContentView()
                .onAppear { NSLog("🟢 Zyng: главный экран показан") }
        }
    }
}
